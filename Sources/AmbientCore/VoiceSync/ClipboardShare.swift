import Foundation

/// The rules for sharing the clipboard between paired Macs: what may leave this Mac, and which copies from another Mac
/// go on this one's clipboard. The app watches the pasteboard and writes to it; these decide.
public enum ClipboardShare {
    /// Put on the pasteboard next to text that came from another Mac, so it isn't sent straight back.
    public static let marker = "com.viveky259259.Ambient.clipboard"
    /// Plain text, the only kind shared.
    public static let textType = "public.utf8-plain-text"
    /// What apps mark a copy with when it shouldn't be shared or kept (nspasteboard.org): passwords and other secrets,
    /// a copy that's about to be replaced, or one made by a program rather than the user. And what came from another Mac.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type", marker,
    ]
    /// A copy older than this when it arrives isn't put on the clipboard: it would replace something copied since, as
    /// when a Mac comes back from sleep to the copies made while it was away.
    public static let freshFor: TimeInterval = 120
    /// How long copied text stays in the sending Mac's outbox.
    public static let keepInOutbox: TimeInterval = 600

    /// Whether a copy with these pasteboard types may go to the other Macs: text, with no mark that it's private.
    public static func shareable(types: [String]) -> Bool {
        types.contains(textType) && privateTypes.isDisjoint(with: types)
    }

    /// Decides which copies from each Mac go on this Mac's clipboard: recent ones, in the order they were made. Not
    /// thread-safe: one owner.
    public struct Arrivals {
        private var last: [String: Date] = [:]

        public init() {}

        /// True when the copy made on `machine` at `at` should go on the clipboard now. Its clock may be a little off
        /// this one's, so a copy from a few seconds ahead counts as now; one made before its last applied copy doesn't.
        public mutating func accept(_ machine: String, at: Date, now: Date = Date()) -> Bool {
            guard now.timeIntervalSince(at) <= freshFor, at.timeIntervalSince(now) <= freshFor else { return false }
            if let previous = last[machine], at < previous { return false }
            last[machine] = at
            return true
        }
    }
}
